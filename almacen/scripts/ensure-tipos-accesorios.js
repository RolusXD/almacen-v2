const { Client } = require('pg');

const connectionString = process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL;

if (!connectionString) {
  console.error('Defina DATABASE_URL_UNPOOLED o DATABASE_URL.');
  process.exit(1);
}

const sql = `
CREATE TABLE IF NOT EXISTS tipos_accesorios (
  id_tipo_accesorio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(40) NOT NULL UNIQUE,
  descripcion VARCHAR(180) NOT NULL,
  categoria VARCHAR(80),
  observaciones TEXT,
  activo SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO tipos_accesorios (codigo, descripcion, categoria, observaciones)
SELECT DISTINCT
  codigo,
  MAX(nombre) AS descripcion,
  MAX(COALESCE(unidad_medida, 'GENERAL')) AS categoria,
  MAX(observaciones) AS observaciones
FROM accesorios
WHERE codigo IS NOT NULL AND codigo <> ''
GROUP BY codigo
ON CONFLICT (codigo) DO NOTHING;

SELECT COUNT(*)::int AS total FROM tipos_accesorios;
`;

const client = new Client({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

client.connect()
  .then(() => client.query(sql))
  .then((result) => {
    console.log(`tipos_accesorios=${result[2].rows[0].total}`);
  })
  .finally(() => client.end())
  .catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
