<?php
/**
 * Catálogo de tipos de accesorios.
 */
class TipoAccesorio extends Model {
    protected $table = 'tipos_accesorios';
    protected $primaryKey = 'id_tipo_accesorio';

    public function __construct() {
        parent::__construct();
        $this->ensureTable();
    }

    private function ensureTable() {
        $this->db->exec("
            CREATE TABLE IF NOT EXISTS tipos_accesorios (
                id_tipo_accesorio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                codigo VARCHAR(40) NOT NULL UNIQUE,
                descripcion VARCHAR(180) NOT NULL,
                categoria VARCHAR(80),
                observaciones TEXT,
                activo SMALLINT NOT NULL DEFAULT 1,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        ");

        $this->db->exec("
            INSERT INTO tipos_accesorios (codigo, descripcion, categoria, observaciones)
            SELECT DISTINCT
                codigo,
                MAX(nombre) AS descripcion,
                MAX(COALESCE(unidad_medida, 'GENERAL')) AS categoria,
                MAX(observaciones) AS observaciones
            FROM accesorios
            WHERE codigo IS NOT NULL AND codigo <> ''
            GROUP BY codigo
            ON CONFLICT (codigo) DO NOTHING
        ");
    }

    public function obtenerActivos() {
        $sql = "SELECT * FROM {$this->table} WHERE activo = 1 ORDER BY codigo ASC";
        return $this->db->query($sql)->fetchAll();
    }

    public function findByCodigo($codigo) {
        $stmt = $this->db->prepare("SELECT * FROM {$this->table} WHERE codigo = ?");
        $stmt->execute([$codigo]);
        return $stmt->fetch();
    }

    public function registrar($data) {
        if ($this->findByCodigo($data['codigo'])) {
            return ['success' => false, 'message' => 'Ya existe un tipo de accesorio con ese código'];
        }

        $data['activo'] = 1;
        $this->insert($data);

        return ['success' => true, 'message' => 'Tipo de accesorio registrado correctamente'];
    }
}
