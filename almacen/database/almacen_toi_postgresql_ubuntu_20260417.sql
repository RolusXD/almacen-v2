CREATE TABLE categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categorias_general (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    tipo VARCHAR(20) NOT NULL DEFAULT 'EQUIPO',
    codigo_base VARCHAR(20),
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_categorias_general_tipo CHECK (tipo IN ('EQUIPO','ACCESORIO','AMBOS'))
);

CREATE TABLE destinos (
    id_destino INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE marcas (
    id_marca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    pais_origen VARCHAR(50),
    pagina_web VARCHAR(100),
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE proveedores (
    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_empresa VARCHAR(150) NOT NULL,
    nit VARCHAR(20),
    nombre_contacto VARCHAR(100),
    cargo_contacto VARCHAR(50),
    telefono VARCHAR(20),
    celular VARCHAR(20),
    email VARCHAR(100),
    direccion VARCHAR(200),
    ciudad VARCHAR(50),
    pais VARCHAR(50) DEFAULT 'Bolivia',
    pagina_web VARCHAR(100),
    productos TEXT,
    observaciones TEXT,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tipos_equipos (
    id_codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    prefijo VARCHAR(10),
    descripcion VARCHAR(150) NOT NULL,
    categoria VARCHAR(20) NOT NULL DEFAULT 'OTRO',
    observaciones TEXT,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_tipos_equipos_categoria CHECK (categoria IN ('ROUTER','ONU','SWITCH','OTRO'))
);

CREATE TABLE unidades_medida (
    id_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    abreviatura VARCHAR(10),
    descripcion TEXT,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tipos_accesorios (
    id_tipo_accesorio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    descripcion VARCHAR(180) NOT NULL,
    categoria VARCHAR(80),
    observaciones TEXT,
    activo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    carnet VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    fecha_nacimiento DATE NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'usuario',
    activo SMALLINT NOT NULL DEFAULT 1,
    ultimo_acceso TIMESTAMP,
    reset_token VARCHAR(128),
    reset_token_expires TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_usuarios_rol CHECK (rol IN ('admin','usuario'))
);

CREATE TABLE equipos (
    id_equipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    id_categoria INTEGER REFERENCES categorias(id_categoria) ON DELETE SET NULL,
    id_marca INTEGER REFERENCES marcas(id_marca) ON DELETE SET NULL,
    id_proveedor INTEGER REFERENCES proveedores(id_proveedor) ON DELETE SET NULL,
    costo NUMERIC(10,2),
    numero_serie_mac VARCHAR(50) NOT NULL UNIQUE,
    codigo VARCHAR(20) REFERENCES tipos_equipos(codigo) ON UPDATE CASCADE ON DELETE SET NULL,
    id_tipo_equipo INTEGER REFERENCES tipos_equipos(id_codigo) ON DELETE SET NULL,
    modelo VARCHAR(100),
    marca VARCHAR(100),
    fecha_entrada DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    calidad VARCHAR(20) NOT NULL DEFAULT 'BUENO',
    observaciones TEXT,
    precio NUMERIC(10,2),
    proveedor VARCHAR(100),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_equipos_estado CHECK (estado IN ('DISPONIBLE','OCUPADO','MANTENIMIENTO','RETIRADO')),
    CONSTRAINT chk_equipos_calidad CHECK (calidad IN ('NUEVO','BUENO','REGULAR','MALO'))
);

CREATE TABLE accesorios (
    id_accesorio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    id_categoria INTEGER REFERENCES categorias(id_categoria) ON DELETE SET NULL,
    id_marca INTEGER REFERENCES marcas(id_marca) ON DELETE SET NULL,
    id_proveedor INTEGER REFERENCES proveedores(id_proveedor) ON DELETE SET NULL,
    costo NUMERIC(10,2),
    codigo VARCHAR(20),
    cantidad INTEGER NOT NULL DEFAULT 0,
    unidad_medida VARCHAR(50),
    modelo VARCHAR(100),
    marca VARCHAR(100),
    numero_serie_mac VARCHAR(50),
    fecha_entrada DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    calidad VARCHAR(20) NOT NULL DEFAULT 'BUENO',
    observaciones TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_accesorios_estado CHECK (estado IN ('DISPONIBLE','OCUPADO','MANTENIMIENTO','RETIRADO')),
    CONSTRAINT chk_accesorios_calidad CHECK (calidad IN ('NUEVO','BUENO','REGULAR','MALO')),
    CONSTRAINT chk_accesorios_cantidad CHECK (cantidad >= 0)
);

CREATE TABLE movimientos_equipos (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo INTEGER REFERENCES equipos(id_equipo) ON DELETE SET NULL,
    numero_serie_mac VARCHAR(50) NOT NULL REFERENCES equipos(numero_serie_mac) ON UPDATE CASCADE,
    tipo_movimiento VARCHAR(20) NOT NULL,
    asunto VARCHAR(100) NOT NULL,
    encargado VARCHAR(100) NOT NULL,
    destino VARCHAR(100),
    observaciones TEXT,
    observaciones_detalladas TEXT,
    fecha_movimiento DATE NOT NULL,
    created_by INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_movimientos_equipos_tipo CHECK (tipo_movimiento IN ('SALIDA','ENTRADA','MANTENIMIENTO','REVISION'))
);

CREATE TABLE movimientos_accesorios (
    id_movimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_accesorio INTEGER NOT NULL REFERENCES accesorios(id_accesorio) ON DELETE RESTRICT,
    tipo_movimiento VARCHAR(20) NOT NULL,
    cantidad INTEGER NOT NULL,
    asunto VARCHAR(100) NOT NULL,
    encargado VARCHAR(100) NOT NULL,
    destino VARCHAR(100),
    observaciones TEXT,
    observaciones_detalladas TEXT,
    fecha_movimiento DATE NOT NULL,
    created_by INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_movimientos_accesorios_tipo CHECK (tipo_movimiento IN ('SALIDA','ENTRADA','MANTENIMIENTO','REVISION')),
    CONSTRAINT chk_movimientos_accesorios_cantidad CHECK (cantidad > 0)
);

CREATE TABLE mantenimientos (
    id_mantenimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo INTEGER REFERENCES equipos(id_equipo) ON DELETE SET NULL,
    numero_serie_mac VARCHAR(50) NOT NULL REFERENCES equipos(numero_serie_mac) ON UPDATE CASCADE,
    tipo_mantenimiento VARCHAR(20) NOT NULL,
    descripcion TEXT NOT NULL,
    tecnico_responsable VARCHAR(100) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_entrega DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'EN_PROCESO',
    costo NUMERIC(10,2),
    repuestos_cambiados TEXT,
    observaciones TEXT,
    garantia_dias INTEGER DEFAULT 0,
    created_by INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_mantenimientos_tipo CHECK (tipo_mantenimiento IN ('PREVENTIVO','CORRECTIVO','EVOLUTIVO')),
    CONSTRAINT chk_mantenimientos_estado CHECK (estado IN ('EN_PROCESO','COMPLETADO','CANCELADO'))
);

CREATE TABLE prestamos (
    id_prestamo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_equipo INTEGER REFERENCES equipos(id_equipo) ON DELETE SET NULL,
    numero_serie_mac VARCHAR(50) NOT NULL REFERENCES equipos(numero_serie_mac) ON UPDATE CASCADE,
    id_usuario_solicita INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    nombre_solicita VARCHAR(100) NOT NULL,
    cargo_solicita VARCHAR(50),
    departamento VARCHAR(100),
    telefono_contacto VARCHAR(20),
    email_contacto VARCHAR(100),
    fecha_prestamo DATE NOT NULL,
    fecha_devolucion_esperada DATE NOT NULL,
    fecha_devolucion_real DATE,
    estado VARCHAR(20) NOT NULL DEFAULT 'PRESTADO',
    motivo_prestamo TEXT NOT NULL,
    observaciones_salida TEXT,
    observaciones_devolucion TEXT,
    equipo_entregado_conforme SMALLINT NOT NULL DEFAULT 1,
    equipo_recibido_conforme SMALLINT NOT NULL DEFAULT 1,
    id_usuario_entrega INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    id_usuario_recibe INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    created_by INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_prestamos_estado CHECK (estado IN ('PRESTADO','DEVUELTO','ATRASADO','PERDIDO'))
);

CREATE TABLE app_sessions (
    id VARCHAR(128) PRIMARY KEY,
    payload TEXT NOT NULL,
    last_activity INTEGER NOT NULL
);

