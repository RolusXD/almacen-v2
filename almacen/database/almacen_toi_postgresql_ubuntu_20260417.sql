CREATE VIEW vista_accesorios_stock_bajo AS
SELECT id_accesorio, nombre, cantidad, unidad_medida, estado
FROM accesorios
WHERE cantidad < 10
ORDER BY cantidad;

CREATE VIEW vista_equipos_completo AS
SELECT e.*, c.nombre AS categoria_nombre, m.nombre AS marca_nombre, p.nombre_empresa AS proveedor_nombre
FROM equipos e
LEFT JOIN categorias c ON e.id_categoria = c.id_categoria
LEFT JOIN marcas m ON e.id_marca = m.id_marca
LEFT JOIN proveedores p ON e.id_proveedor = p.id_proveedor;

CREATE VIEW vista_equipos_disponibles AS
SELECT id_equipo, nombre, codigo, numero_serie_mac, modelo, marca, calidad, precio, fecha_entrada,
       (CURRENT_DATE - fecha_entrada) AS dias_almacenado
FROM equipos
WHERE estado = 'DISPONIBLE'
ORDER BY nombre, fecha_entrada;

CREATE VIEW vista_resumen_equipos_por_codigo AS
SELECT e.codigo,
       t.descripcion,
       COUNT(*) AS total,
       SUM(CASE WHEN e.estado = 'DISPONIBLE' THEN 1 ELSE 0 END) AS disponibles,
       SUM(CASE WHEN e.estado = 'OCUPADO' THEN 1 ELSE 0 END) AS ocupados,
       SUM(CASE WHEN e.estado = 'MANTENIMIENTO' THEN 1 ELSE 0 END) AS mantenimiento,
       SUM(CASE WHEN e.calidad = 'NUEVO' THEN 1 ELSE 0 END) AS nuevos,
       AVG(e.precio) AS precio_promedio
FROM equipos e
LEFT JOIN tipos_equipos t ON e.codigo = t.codigo
GROUP BY e.codigo, t.descripcion
ORDER BY COUNT(*) DESC;

CREATE VIEW vista_resumen_movimientos_mes AS
SELECT TO_CHAR(fecha_movimiento, 'YYYY-MM') AS mes,
       tipo_movimiento,
       COUNT(*) AS total_movimientos
FROM movimientos_equipos
GROUP BY TO_CHAR(fecha_movimiento, 'YYYY-MM'), tipo_movimiento;

